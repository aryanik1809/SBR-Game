"""Read/write src/shared/AudioIds.luau (Roblox asset IDs for assets/audio/*.ogg)."""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IDS_PATH = os.path.join(ROOT, "src", "shared", "AudioIds.luau")
MANIFEST = os.path.join(ROOT, "assets", "audio", "manifest.json")


def read_ids():
    """{name: id} currently stored in AudioIds.luau (empty if the file doesn't exist yet)."""
    if not os.path.exists(IDS_PATH):
        return {}
    text = open(IDS_PATH).read()
    return {m.group(1): int(m.group(2)) for m in re.finditer(r"^\s*(\w+) = \{ id = (\d+),", text, re.M)}


def write_ids(ids):
    manifest = json.load(open(MANIFEST))
    lines = [
        "-- GENERATED by tools/upload_audio.py from assets/audio/manifest.json. Don't hand-edit the table shape;",
        "-- an `id` of 0 just means \"not uploaded yet\": the game stays silent for that sound instead of erroring.",
        "-- Paste an ID in by hand if you uploaded a file yourself (Creator Hub > Audio).",
        "return {",
    ]
    for name in sorted(manifest):
        m = manifest[name]
        extra = ", positional = true" if m.get("positional") else ""
        lines.append(
            f'\t{name} = {{ id = {int(ids.get(name, 0))}, volume = {m["volume"]}, loop = {str(bool(m["loop"])).lower()}, '
            f'kind = "{m["kind"]}", seconds = {m["seconds"]}{extra} }},'
        )
    lines.append("}")
    lines.append("")
    with open(IDS_PATH, "w") as f:
        f.write("\n".join(lines))
    return IDS_PATH
