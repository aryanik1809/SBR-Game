#!/usr/bin/env python3
"""Cut sprite sheets into individual sprites and write src/shared/SpriteSheets.luau.

Usage: python3 tools/slice_sprites.py
Reads assets/manifest.json, finds each separate object in the sheet's transparent PNG,
writes the Luau sprite table plus assets/_preview/<sheet>.png with numbered boxes so
you can check the order and fix `names` in the manifest.
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
OUT = ROOT / "src" / "shared" / "SpriteSheets.luau"
DOWN = 4          # label on a mask shrunk by this factor (fast, no scipy needed)
MERGE = 4         # cells of gap that still count as the same object (shadow, thin arms)
MIN_AREA = 400    # ignore specks smaller than this many source pixels
ALPHA_MIN = 24


def dilate(mask: np.ndarray, r: int) -> np.ndarray:
    out = mask.copy()
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            out |= np.roll(np.roll(mask, dy, 0), dx, 1)
    return out


def label(mask: np.ndarray) -> np.ndarray:
    labels = np.zeros(mask.shape, dtype=np.int32)
    h, w = mask.shape
    n = 0
    for y in range(h):
        for x in range(w):
            if mask[y, x] and not labels[y, x]:
                n += 1
                stack = [(y, x)]
                labels[y, x] = n
                while stack:
                    cy, cx = stack.pop()
                    for ny, nx in ((cy + 1, cx), (cy - 1, cx), (cy, cx + 1), (cy, cx - 1)):
                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not labels[ny, nx]:
                            labels[ny, nx] = n
                            stack.append((ny, nx))
    return labels


def find_boxes(img: Image.Image, merge: int = MERGE):
    alpha = np.array(img.convert("RGBA"))[:, :, 3] > ALPHA_MIN
    h, w = alpha.shape
    small = alpha[: h // DOWN * DOWN, : w // DOWN * DOWN]
    small = small.reshape(h // DOWN, DOWN, w // DOWN, DOWN).any(axis=(1, 3))
    labels = label(dilate(small, merge))
    boxes = []
    for i in range(1, labels.max() + 1):
        ys, xs = np.where((labels == i) & small)
        if len(ys) == 0:
            continue
        x0, x1 = xs.min() * DOWN, (xs.max() + 1) * DOWN
        y0, y1 = ys.min() * DOWN, (ys.max() + 1) * DOWN
        # tighten to real opaque pixels
        sub = alpha[y0:y1, x0:x1]
        yy, xx = np.where(sub)
        if len(yy) < MIN_AREA:
            continue
        boxes.append((x0 + xx.min(), y0 + yy.min(), x0 + xx.max() + 1, y0 + yy.max() + 1))
    # reading order: rows of similar top edge, then left to right
    boxes.sort(key=lambda b: (round(b[1] / 150), b[0]))
    return boxes


def main() -> int:
    manifest = json.loads((ASSETS / "manifest.json").read_text())
    (ASSETS / "_preview").mkdir(exist_ok=True)
    lines = [
        "-- GENERATED by tools/slice_sprites.py from assets/manifest.json. Do not edit by hand.",
        "return {",
    ]
    for sheet, cfg in manifest["sheets"].items():
        path = ASSETS / cfg["file"]
        if not path.exists():
            print(f"skip {sheet}: {path.name} not found")
            continue
        img = Image.open(path).convert("RGBA")
        boxes = find_boxes(img, cfg.get("merge", MERGE))
        names = cfg.get("names", [])
        if names and len(names) != len(boxes):
            print(f"WARNING {sheet}: found {len(boxes)} objects but manifest lists {len(names)} names")
        preview = img.copy()
        draw = ImageDraw.Draw(preview)
        for i, (x0, y0, x1, y1) in enumerate(boxes):
            name = names[i] if i < len(names) else f"{sheet}_{i + 1}"
            draw.rectangle((x0, y0, x1, y1), outline=(255, 0, 255, 255), width=4)
            draw.text((x0 + 8, y0 + 8), f"{i + 1}:{name}", fill=(255, 0, 255, 255))
            override = cfg.get("overrides", {}).get(name, {})
            ppu = override.get("ppu", cfg.get("ppu", 40))
            ax = override.get("ax", (x1 - x0) // 2)
            collide = override.get("collide", cfg.get("collide"))
            lines.append(f'\t["{name}"] = {{')
            lines.append(f'\t\timage = "rbxassetid://{cfg["id"]}",')
            lines.append(f"\t\trect = {{ x = {x0}, y = {y0}, w = {x1 - x0}, h = {y1 - y0} }},")
            lines.append(f"\t\tppu = {ppu}, ax = {ax}, collide = {'nil' if collide is None else collide},")
            lines.append("\t},")
            print(f"{sheet}[{i + 1}] {name}: rect=({x0},{y0},{x1 - x0},{y1 - y0})")
        preview.save(ASSETS / "_preview" / f"{sheet}.png")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
