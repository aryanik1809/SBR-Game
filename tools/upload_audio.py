#!/usr/bin/env python3
"""Upload assets/audio/*.ogg to Roblox and record the asset IDs in src/shared/AudioIds.luau.

Roblox can only play audio that has been uploaded, so this is the one manual step for sound.

    python3 tools/upload_audio.py --init                      # (re)generate AudioIds.luau, keeping known IDs
    python3 tools/upload_audio.py --upload --api-key KEY --user-id 123456
    python3 tools/upload_audio.py --upload --api-key KEY --group-id 987654 --only theme_title theme_race

KEY = an Open Cloud API key with the "asset:read" + "asset:write" permissions
      (create.roblox.com > Credentials). You also need to be ID-verified to upload audio.
Uploaded audio goes through Roblox moderation; a sound can stay silent for a few minutes until it passes.
Uses only the standard library. NOTE: written against the documented Open Cloud Assets API but not run
against a real account in this repo's CI, so check the first upload's output.
"""
import argparse
import json
import mimetypes
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audio_ids  # noqa: E402

API = "https://apis.roblox.com/assets/v1"
AUDIO_DIR = os.path.join(audio_ids.ROOT, "assets", "audio")


def multipart(fields, file_field, filename, data, content_type):
    boundary = uuid.uuid4().hex
    out = []
    for k, v in fields.items():
        out.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{k}"\r\n\r\n{v}\r\n'.encode())
    out.append(
        (f'--{boundary}\r\nContent-Disposition: form-data; name="{file_field}"; filename="{filename}"\r\n'
         f"Content-Type: {content_type}\r\n\r\n").encode()
    )
    out.append(data)
    out.append(f"\r\n--{boundary}--\r\n".encode())
    return b"".join(out), f"multipart/form-data; boundary={boundary}"


def call(req, retries=5):
    for attempt in range(retries):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.loads(r.read().decode())
        except urllib.error.HTTPError as e:
            body = e.read().decode(errors="replace")
            if e.code == 429 and attempt < retries - 1:
                time.sleep(2 ** attempt)
                continue
            raise SystemExit(f"HTTP {e.code} from Roblox: {body}")
    raise SystemExit("too many retries")


def upload(name, path, key, creator):
    data = open(path, "rb").read()
    request = {
        "assetType": "Audio",
        "displayName": f"SBR {name}",
        "description": "Sound for the SBR Game (generated by tools/make_audio.py)",
        "creationContext": {"creator": creator},
    }
    body, ctype = multipart({"request": json.dumps(request)}, "fileContent", os.path.basename(path), data, "audio/ogg")
    req = urllib.request.Request(f"{API}/assets", data=body, method="POST", headers={"x-api-key": key, "Content-Type": ctype})
    op = call(req)
    op_id = op["path"].split("/")[-1]
    for _ in range(60):
        if op.get("done"):
            break
        time.sleep(2)
        op = call(urllib.request.Request(f"{API}/operations/{op_id}", headers={"x-api-key": key}))
    if not op.get("done"):
        raise SystemExit(f"{name}: upload still processing; re-run later (operation {op_id})")
    if "error" in op:
        raise SystemExit(f"{name}: {op['error']}")
    return int(op["response"]["assetId"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--init", action="store_true")
    ap.add_argument("--upload", action="store_true")
    ap.add_argument("--api-key", default=os.environ.get("ROBLOX_API_KEY"))
    ap.add_argument("--user-id")
    ap.add_argument("--group-id")
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--force", action="store_true", help="re-upload sounds that already have an ID")
    a = ap.parse_args()

    ids = audio_ids.read_ids()
    manifest = json.load(open(audio_ids.MANIFEST))
    if a.upload:
        if not a.api_key or not (a.user_id or a.group_id):
            sys.exit("--upload needs --api-key (or $ROBLOX_API_KEY) and --user-id or --group-id")
        creator = {"userId": a.user_id} if a.user_id else {"groupId": a.group_id}
        names = a.only or sorted(manifest)
        for i, name in enumerate(names, 1):
            if ids.get(name) and not a.force:
                print(f"[{i}/{len(names)}] {name}: already has id {ids[name]}")
                continue
            path = os.path.join(AUDIO_DIR, manifest[name]["file"])
            print(f"[{i}/{len(names)}] uploading {name} ...", flush=True)
            ids[name] = upload(name, path, a.api_key, creator)
            print(f"    -> rbxassetid://{ids[name]}")
            audio_ids.write_ids(ids)  # save as we go so an interrupted run loses nothing
            time.sleep(1)
    out = audio_ids.write_ids(ids)
    done = sum(1 for n in manifest if ids.get(n))
    print(f"wrote {out}: {done}/{len(manifest)} sounds have an asset id")


if __name__ == "__main__":
    main()
